// Export a table to a real .xlsx file, or to PDF via the browser's print dialog ("Save as PDF").
// Both carry the standard report header: title, filter summary, generated-by and date (Documentation §9.2).
import writeXlsxFile from 'write-excel-file';
import { getUser, logExport } from '../store.js';

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const esc = (v) => String(v ?? '').replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
const stamp = () => new Date().toLocaleString('en-PH', { dateStyle: 'long', timeStyle: 'short' });

/**
 * spec: { title, filters: string[], head: string[], rows: (string|number)[][], totals?: (string|number)[] }
 * format: 'xlsx' | 'pdf'
 */
export async function exportTable(spec, format) {
  const user = getUser();
  const { title, filters = [], head, rows, totals } = spec;
  const body = totals ? [...rows, totals] : rows;
  const summary = filters.length ? filters.join(' · ') : 'No filters applied';

  if (format === 'xlsx') {
    const cell = (v, extra = {}) => (v === null || v === undefined || v === '' ? null : typeof v === 'number' ? { type: Number, value: v, ...extra } : { type: String, value: String(v), ...extra });
    const data = [
      [{ value: 'Pamantasan ng Lungsod ng Maynila — Research Management System', fontWeight: 'bold', fontSize: 13 }],
      [{ value: title, fontWeight: 'bold', fontSize: 12 }],
      [{ value: `Filters: ${summary}` }],
      [{ value: `Generated by ${user.name} on ${stamp()}` }],
      [],
      head.map((h) => ({ value: h, fontWeight: 'bold', color: '#FFFFFF', backgroundColor: '#1F3A93' })),
      ...body.map((r, i) => r.map((v) => cell(v, totals && i === body.length - 1 ? { fontWeight: 'bold', backgroundColor: '#E9EDF7' } : {}))),
    ];
    const columns = head.map((h, i) => ({ width: Math.min(60, Math.max(h.length + 2, ...body.map((r) => String(r[i] ?? '').length + 2))) }));
    await writeXlsxFile(data, { fileName: `${slug(title)}-${new Date().toISOString().slice(0, 10)}.xlsx`, columns });
  } else {
    await printPdf({ title, summary, head, body, hasTotals: !!totals, user });
  }
  logExport(title, format === 'xlsx' ? 'Excel' : 'PDF', rows.length);
}

function printPdf({ title, summary, head, body, hasTotals, user }) {
  const seal = new URL('plm-seal.png', document.baseURI).href;
  const wide = head.length > 6;
  const html = `<!doctype html><html><head><meta charset="utf-8"><title>${esc(title)}</title><style>
    @page { size: A4 ${wide ? 'landscape' : 'portrait'}; margin: 16mm 14mm 18mm; @bottom-right { content: "Page " counter(page) " of " counter(pages); font: 10px sans-serif; color: #5C6B7A; } }
    body { font-family: 'Source Sans 3', Arial, sans-serif; color: #1F2933; font-size: 11px; }
    header { display: flex; align-items: center; gap: 14px; border-bottom: 3px solid #1F3A93; padding-bottom: 10px; margin-bottom: 12px; }
    header img { width: 64px; height: 64px; }
    .uni { font-size: 11px; letter-spacing: .06em; text-transform: uppercase; color: #5C6B7A; font-weight: 600; }
    .sys { font-size: 17px; font-weight: 700; color: #1F3A93; }
    h1 { font-size: 16px; margin: 0 0 4px; } .meta { color: #5C6B7A; margin-bottom: 10px; line-height: 1.5; }
    table { width: 100%; border-collapse: collapse; } th { background: #1F3A93; color: #fff; text-align: left; padding: 6px 8px; font-size: 10px; text-transform: uppercase; letter-spacing: .04em; }
    td { padding: 5px 8px; border-bottom: 1px solid #D9DEE4; vertical-align: top; } tr:nth-child(even) td { background: #F7F8FA; }
    tr.total td { font-weight: 700; background: #E9EDF7; border-top: 2px solid #1F3A93; } thead { display: table-header-group; } tr { page-break-inside: avoid; }
  </style></head><body>
  <header><img src="${seal}" alt="PLM seal"><div><div class="uni">Pamantasan ng Lungsod ng Maynila</div><div class="sys">Research Management System</div></div></header>
  <h1>${esc(title)}</h1>
  <div class="meta">Filters: ${esc(summary)}<br>Generated by ${esc(user.name)} (${esc(user.email)}) on ${esc(stamp())} · ${body.length - (hasTotals ? 1 : 0)} row(s)</div>
  <table><thead><tr>${head.map((h) => `<th>${esc(h)}</th>`).join('')}</tr></thead><tbody>
  ${body.map((r, i) => `<tr${hasTotals && i === body.length - 1 ? ' class="total"' : ''}>${r.map((v) => `<td>${esc(v)}</td>`).join('')}</tr>`).join('')}
  </tbody></table></body></html>`;

  return new Promise((resolve) => {
    const frame = document.createElement('iframe');
    frame.style.cssText = 'position:fixed;right:0;bottom:0;width:0;height:0;border:0';
    frame.srcdoc = html;
    frame.onload = () => {
      const img = frame.contentDocument.querySelector('img');
      const go = () => { frame.contentWindow.focus(); frame.contentWindow.print(); setTimeout(() => frame.remove(), 60000); resolve(); };
      if (img && !img.complete) { img.onload = go; img.onerror = go; } else go();
    };
    document.body.appendChild(frame);
  });
}
